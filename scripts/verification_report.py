"""Cross-check the database against independent sources -> data/verification_report.csv + docs/DATA_VERIFICATION.md

A. Species data: values first entered (NBS 1982 tables, from memory) vs NIST-JANAF tables read online.
B. Reactions: database values vs independent open-access papers.
C. Internal consistency of extracted literature data (Van 't Hoff check of Donkers et al. 2017 rows).
"""
from pathlib import Path
import math
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
R = 8.314462618
db = pd.read_csv(ROOT / "data" / "tces_database.csv").set_index("id")
sp = pd.read_csv(ROOT / "data" / "thermo_species.csv")

rows = []
# A ---------------------------------------------------------------------------
for _, s in sp[sp.source.str.startswith("NIST-JANAF")].iterrows():
    dh, ds = s.dHf_kJ_mol - s.dHf_NBS_kJ_mol, s.S_J_molK - s.S_NBS_J_molK
    if abs(dh) > 0.5 or abs(ds) > 0.5:
        rows.append(("A", s.species, "dHf / S (298 K)", f"{s.dHf_NBS_kJ_mol} / {s.S_NBS_J_molK}",
                     f"{s.dHf_kJ_mol} / {s.S_J_molK}", f"{dh:+.2f} kJ/mol, {ds:+.2f} J/mol/K",
                     s.source_url, "JANAF value now used"))

# B ---------------------------------------------------------------------------
def B(rid, prop, ours, ref, unit, src, note):
    rows.append(("B", f"{rid} {db.loc[rid, 'name']}", prop, f"{ours:.3g} {unit}", f"{ref} {unit}",
                 f"{100 * (ours - float(str(ref).split('-')[0])) / float(str(ref).split('-')[0]):+.0f} %", src, note))

B("S03", "ED_vol CuSO4.5H2O -> CuSO4", db.loc["S03", "ED_vol_GJ_m3"], 2.56, "GJ/m3",
  "Donkers 2017 App. A p.59 (row CuSO4 5->0, combined)", "database uses NBS data + crystal density")
B("S02", "ED_vol CaSO4.2H2O -> CaSO4", db.loc["S02", "ED_vol_GJ_m3"], "1.25-1.29", "GJ/m3",
  "Donkers 2017 App. A p.58 (rows CaSO4 2->0)", "")
B("O01", "ED_grav Co3O4 -> CoO", db.loc["O01", "ED_grav_MJ_kg"] * 1000, 597, "kJ/kg",
  "André et al. 2017 (measured, DSC)", "JANAF 298 K data overestimate; JANAF T_eq 1063 C vs ~920 C reduction onset in air")
B("O02", "ED_grav Mn2O3 -> Mn3O4", db.loc["O02", "ED_grav_MJ_kg"] * 1000, 190.1, "kJ/kg",
  "André et al. 2017 (theoretical at 915 C; measured 148)", "")

# C ---------------------------------------------------------------------------
for rid, dh, ds, thyd in [("S16", 55.5, 148, 29), ("S17", 55.3, 148, 28), ("S18", 53.6, 143, 26)]:
    t = dh * 1e3 / (ds - R * math.log(0.012)) - 273.15
    rows.append(("C", f"{rid} {db.loc[rid, 'name']}", "Thyd at 12 mbar from dH, dS (per mol H2O)",
                 f"{t:.1f} C", f"{thyd} C (printed)", f"{t - thyd:+.1f} K", "Donkers 2017 App. A",
                 "confirms dH, dS are per mol H2O"))
t = 71.98e3 / 143.93 - 273.15
rows.append(("C", "S19 SrBr2.H2O", "291 kJ/kg SrBr2 vs dH/M", f"{71.98 / 247.43 * 1000:.0f} kJ/kg", "291 kJ/kg",
             f"{71.98 / 247.43 * 1000 - 291:+.0f} kJ/kg", "Stengler et al. (DLR)", f"T_eq(1 bar) = {t:.0f} C"))

out = pd.DataFrame(rows, columns=["check", "item", "property", "database", "reference", "difference", "source", "comment"])
out.to_csv(ROOT / "data" / "verification_report.csv", index=False)

status = db["verification"].fillna("").str.split(";").str[0].str.replace(r" for .*", "", regex=True).value_counts()
md = ["# Data verification report", "",
      "Generated by `python scripts/verification_report.py`.", "",
      "## Verification status of the 38 database entries", "",
      "| Status | Entries |", "|---|---|"]
md += [f"| {k} | {v} |" for k, v in status.items()]
md += ["", "Entries marked **NOT verified** are kept for completeness but must be checked against the original paper before use.",
       "", "## Cross-checks", "", out.to_markdown(index=False), "",
       "* **A** – species values first entered from the NBS tables, replaced by NIST-JANAF values read from janaf.nist.gov.",
       "* **B** – database values compared with independent open-access papers.",
       "* **C** – consistency of values extracted from papers."]
(ROOT / "docs").mkdir(exist_ok=True)
(ROOT / "docs" / "DATA_VERIFICATION.md").write_text("\n".join(md) + "\n")
print(out.to_string(index=False))
